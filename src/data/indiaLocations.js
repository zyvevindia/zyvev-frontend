/** @type {string[]} */
export const indiaStates = Object.keys(indiaLocations).sort((a, b) =>
  a.localeCompare(b, "en", { sensitivity: "base" })
);

/**
 * @param {string} state
 * @returns {string[]}
 */
export function getCitiesForState(state = "") {
  const key = String(state || "").trim();
  return indiaLocations[key] ? [...indiaLocations[key]] : [];
}

/**
 * @param {string} state
 * @returns {boolean}
 */
export function isValidIndiaState(state = "") {
  const key = String(state || "").trim();
  return Boolean(key && indiaLocations[key]);
}

/**
 * @param {string} state
 * @param {string} city
 * @returns {boolean}
 */
export function isValidIndiaCity(state = "", city = "") {
  const cities = getCitiesForState(state);
  const selected = String(city || "").trim();
  return Boolean(selected && cities.includes(selected));
}
